import assert from 'node:assert/strict';
import {issueAccess,validAccess,constantEqual,accessCookie,ADMIN_COOKIE,issueVisitor,visitorIdentity,visitorCookie} from '../lib/admin-access.ts';
const secret='test-only-signing-key-at-least-32-characters';
const now=1700000000000;
const request=token=>new Request('https://example.test/api/catalog',{headers:{cookie:`${ADMIN_COOKIE}=${token}`}});
const token=await issueAccess(secret,now);
assert.equal(await validAccess(request(token),secret,now),true);
assert.equal(await validAccess(request(token),secret,now+3600000),false);
assert.equal(await validAccess(request(token+'x'),secret,now),false);
assert.equal(await validAccess(request(token),'different-key',now),false);
assert.equal(await validAccess(request(token),undefined,now),false);
assert.equal(await validAccess(new Request('https://example.test'),secret,now),false);
assert.equal(await constantEqual('test-password','test-password'),true);
assert.equal(await constantEqual('test-password','incorrect'),false);
assert.match(accessCookie(token),/HttpOnly; Secure; SameSite=Strict/);
assert.match(accessCookie(''),/Max-Age=0/);
const visitor=await issueVisitor(secret,now);
const visitorRequest=value=>new Request('https://example.test/api/favorites',{headers:{cookie:`__Host-pairdeer_visitor=${value}`}});
assert.match(await visitorIdentity(visitorRequest(visitor),secret,now),/^visitor:/);
assert.equal(await visitorIdentity(visitorRequest(visitor+'x'),secret,now),null);
assert.equal(await visitorIdentity(visitorRequest(visitor),secret,now+366*86400000),null);
assert.equal(await validAccess(request(visitor),secret,now),false,'visitor HMAC cannot authenticate administrator');
assert.match(visitorCookie(visitor),/HttpOnly; Secure; SameSite=Lax/);
process.env.ALLOW_INSECURE_COOKIES='1';process.env.NODE_ENV='production';
assert.match(accessCookie(token),/^__Host-.*Secure/,'production cannot disable secure cookies');
process.env.NODE_ENV='test';
assert.doesNotMatch(accessCookie(token),/__Host-|Secure/,'explicit local test override uses valid non-Host cookie name');
console.log('PASS: signed administrator/visitor cookies reject forgery, expiry, wrong keys and role confusion; production cookies remain secure.');
